"""Write gallery/posters.js: every poster under out/<series>/[<group>/]<name>.png, in README order.

The one-line idea for each poster comes from the README tables (the longest cell of its row).
Also writes a small JPEG thumbnail per poster to gallery/thumbs/ (macOS `sips`; skipped elsewhere,
and the gallery falls back to the full PNG).
    python3 src/gallery.py
"""
import json
import re
import shutil
import subprocess
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SERIES = ["core", "minimal", "sensors", "robots", "localization", "drone", "gps", "imu", "vision", "photogrammetry", "still", "lattice", "epic", "rl"]
THUMBS = ROOT / "gallery/thumbs"
THUMB_PX = 720  # long edge


def thumbnail(png: Path, rel: Path) -> None:
    jpg = THUMBS / rel.with_suffix(".jpg")
    if not shutil.which("sips") or (jpg.exists() and jpg.stat().st_mtime >= png.stat().st_mtime):
        return
    jpg.parent.mkdir(parents=True, exist_ok=True)
    subprocess.run(["sips", "-s", "format", "jpeg", "-s", "formatOptions", "82", "-Z", str(THUMB_PX),
                    str(png), "--out", str(jpg)], check=True, capture_output=True)


def readme_ideas() -> dict[str, str]:
    ideas = {}
    for line in (ROOT / "README.md").read_text().splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")] if line.startswith("|") else []
        names = [c for c in cells if re.fullmatch(r"[a-z]+\.", c)]
        if names:
            ideas.setdefault(names[0][:-1], max((c for c in cells if c != names[0]), key=len))
    return ideas


def main() -> None:
    ideas = readme_ideas()
    order = {name: i for i, name in enumerate(ideas)}
    posters = []
    for png in (ROOT / "out").rglob("*.png"):
        rel = png.relative_to(ROOT / "out")
        if png.stem == "overview" or rel.parts[0] not in SERIES:
            continue
        svg = png.with_suffix(".svg")
        thumbnail(png, rel)
        posters.append({
            "id": rel.with_suffix("").as_posix(),
            "name": png.stem,
            "series": rel.parts[0],
            "group": rel.parts[1] if len(rel.parts) > 2 else "",
            "idea": ideas.get(png.stem, ""),
            "thumb": f"thumbs/{rel.with_suffix('.jpg').as_posix()}",
            "png": f"../out/{rel.as_posix()}",
            "svg": f"../out/{rel.with_suffix('.svg').as_posix()}" if svg.exists() else "",
        })
    posters.sort(key=lambda p: (SERIES.index(p["series"]), order.get(p["name"], 1e9), p["name"]))
    out = ROOT / "gallery/posters.js"
    out.write_text("// generated by src/gallery.py — do not edit\nwindow.POSTERS = "
                   + json.dumps(posters, indent=1, ensure_ascii=False) + ";\n")
    missing = [p["name"] for p in posters if not p["idea"]]
    print(out.relative_to(ROOT), len(posters), "posters", "· no idea for: " + " ".join(missing) if missing else "")


if __name__ == "__main__":
    main()
